def mark_case(text_fn):
    def case_text(c, cid, row, with_answer=True):
        text = text_fn(c, cid, row, with_answer)
        flag = ('low confidence, example used' if row['shown'] else 'low confidence, no suitable example' if row.get('gated')
                else 'confident (no example)')
        return text.replace('\nexample shown:', f'\nconfidence gate: {flag}\nexample shown:', 1)
    return case_text


STAGE1_ADDITION = ('\n\nEach case says whether a label-free confidence gate marked it low confidence; examples are shown only '
                   'to such questions. Prefer low-confidence cases when selecting.')


def validation_set(c, t, k, cands, rows, history):
    """One shared set for all candidates of this block: for each candidate the per_candidate past low-confidence
    questions nearest to its source question, pooled (at most max), never from the video of any candidate's source or
    of a case used to write the candidates."""
    cf = c.cf['validation']
    banned = {c.group[x['sample_id']] for x in cands.values()}
    pool = [r for r in history if r.get('gated') and c.group[r['sample_id']] not in banned]
    chosen = []
    for x in cands.values():
        q = c.vec[x['sample_id']]
        near = sorted((r for r in pool if r['sample_id'] not in chosen), key=lambda r: (-float(c.vec[r['sample_id']] @ q), r['sample_id']))
        chosen += [r['sample_id'] for r in near[:cf['per_candidate']]]
    return [next(r for r in pool if r['sample_id'] == s) for s in chosen[:cf['max']]]


def stage4(c, t, k, cands, rows):
    """run1's stage 4 with one shared validation set per block and net = (fixes - breaks) / n."""
    if not cands:
        return {}, {'rounds': []}
    cfg, record = c.cfg['stage4'], {'rounds': []}
    history = S.past_rows(c, t, k - 1) + rows
    shared = validation_set(c, t, k, cands, rows, history)
    record['validation_set'] = [r['sample_id'] for r in shared]
    prompt = S.STAGE4_PROMPT.replace('{position}', 'after the video and before the new question')
    open_ids = list(cands)
    for rnd in range(cfg['max_rounds'] + 1):
        if not open_ids:
            break
        text = '\n\n'.join(S.cand_text(c, cands[i], rnd > 0) for i in open_ids)
        out = S.call(c, 'stage4_refine', prompt, [('text', text)], S.Stage4Output)
        got = {o.candidate_id: o for o in out.candidates}
        rec = {'round': rnd, 'input_chars': len(text), 'output': out.model_dump(), 'invalid': []}
        nxt = []
        for i in open_ids:
            cand, o = cands[i], got.get(i)
            if o is None:
                rec['invalid'].append({'candidate_id': i, 'why': 'no revision returned'})
                cand['next_action'] = cand['next_action'] or 'hold'
                continue
            example = S.answers(o.worked_output, cand['choices'], cand['ground_truth'])
            if not example:
                rec['invalid'].append({'candidate_id': i, 'why': 'revised worked_output does not answer the correct option'})
            else:
                cand['worked_output'] = example
            cand.update(when_to_use=o.when_to_use.strip() or cand['when_to_use'], strategy=o.strategy.strip() or cand['strategy'],
                        next_action=o.next_action)
            cand['rounds'].append({'round': rnd, 'when_to_use': cand['when_to_use'], 'strategy': cand['strategy'],
                                   'worked_output': cand['worked_output'], 'changes': o.changes, 'trial_review': o.trial_review,
                                   'next_action': o.next_action})
            if rnd < cfg['max_rounds'] and o.next_action in ('more_trial', 'revise') or (rnd == 0 and o.next_action == 'memory_review'):
                nxt.append(i)
        record['rounds'].append(rec)
        if rnd == cfg['max_rounds']:
            break
        for i in nxt:
            cand = cands[i]
            res = S.run_trials(c, cand, shared, rnd)
            cand['rounds'][-1]['trials'] = res
            other = [r for r in res if r['role'] == 'other_video']
            fix = sum(r['correct'] and not r['vanilla_correct'] for r in other)
            brk = sum(r['vanilla_correct'] and not r['correct'] for r in other)
            cand['trial_summary'].append({'round': rnd, 'text_digest': digest(cand['worked_output'])[:12],
                                          'source_correct': res[0]['correct'], 'other_n': len(other), 'fixes': fix,
                                          'breaks': brk, 'net_per_question': round((fix - brk) / max(len(other), 1), 3),
                                          'validation_set': 'shared by all candidates of this block'})
        open_ids = nxt
    return cands, record


def render_item(item, full=True):
    """run1's item text with the online record as counts on one denominator."""
    text = ORIG_RENDER(item, full)
    s = item['stats'].get(str(item['version']), {'shown': 0, 'gains': 0, 'harms': 0})
    if s['shown']:
        text += f'online net gain (this version): (fixes - breaks) / uses = ({s["gains"]} - {s["harms"]}) / {s["shown"]}\n'
    return text


def evolve(c, t, k, mem, rows):
    record = {'benchmark': t, 'block': k, 'memory_before': [(i['id'], i['version'], i['status']) for i in mem.listed()]}
    if k < len(c.blocks[t]):
        cases, picked, record['stage1'] = S.stage1(c, t, k, mem, rows)
        views = [S.teacher_view(c.samples[cases[p.case_id]['sample_id']]) for p in picked]
        sols_list, record['stage2'] = S.stage2(c, views) if views else ([], {})
        sols = {p.case_id: s for p, s in zip(picked, sols_list)}
        record['stage2']['solutions'] = dict(sols)
        cands, record['stage3'] = S.stage3(c, t, k, mem, cases, picked, sols) if picked else ({}, {})
        LOCAL.kind = 'trial'
        cands, record['stage4'] = stage4(c, t, k, cands, rows)
        record['candidates'] = cands
        applied, rejected, record['stage5'] = S.stage5(c, t, k, mem, cands, rows)
        record['stage5'].update(applied=applied, rejected=rejected)
    record['memory_after'] = [(i['id'], i['version'], i['status']) for i in mem.listed()]
    return record


# ------------------------------------------------------------------ track loop
def replay_state(c, t, k):
    st = new_state()
    for j in range(1, k + 1):
        after_block(c, t, json.loads(S.block_path(c, 'rows', t, j).read_text()), st)
    return st


def run_track(c, t, max_blocks):
    LOCAL.track = t
    spec = c.tracks[t]
    k = 0
    while S.block_path(c, 'rows', t, k + 1).exists():
        k += 1
    mem = StageMemory(t, json.loads(S.block_path(c, 'memory', t, k).read_text()) if k and spec['memory'] == 'evolve' else [],
                      c.cfg['memory']['max_active'])
    st = replay_state(c, t, k)
    if k:  # cumulative costs of this track, so the per-track teacher cap survives a restart
        c.costs[t].update(json.loads(S.block_path(c, 'stages', t, k).read_text()).get('costs', {}))
    last = min(len(c.blocks[t]), max_blocks or len(c.blocks[t]))
    S.log(c, f'{t}: resume after block {k} of {last} ({spec})')
    for kk in range(k + 1, last + 1):
        t0 = time.time()
        LOCAL.kind = 'icl'
        rows = answer_block(c, t, kk, mem, st)
        if spec['memory'] == 'evolve':
            mem.record_usage(rows)
            record = evolve(c, t, kk, mem, rows)
        else:
            record = {'benchmark': t, 'block': kk, 'memory': 'run1 snapshot (frozen)'}
        record['costs'] = dict(c.costs[t])
        after_block(c, t, rows, st)
        S.atomic_json(S.block_path(c, 'stages', t, kk), json.loads(json.dumps(record, default=str)))
        if spec['memory'] == 'evolve':
            S.atomic_json(S.block_path(c, 'memory', t, kk), mem.snapshot())
        S.atomic_json(S.block_path(c, 'rows', t, kk), rows)  # last: marks the block complete
        if c.cfg.get('export') and (kk == last or kk % c.cfg['export']['every_blocks'] == 0):
            try:
                E.export(c, t, finished=kk == len(c.blocks[t]))
            except Exception as exc:  # a report failure must not stop the run
                S.log(c, f'{t}: export failed ({type(exc).__name__}: {exc})')
        g = [r for r in rows if r['tried']]
        S.log(c, f'{t} block {kk}: final {sum(r["correct"] for r in rows)}/{len(rows)} vanilla {sum(r["vanilla_correct"] for r in rows)} | '
                 f'gated {sum(r["gated"] for r in rows)} example {len(g)} (+{sum(r["correct"] and not r["vanilla_correct"] for r in g)}/-'
                 f'{sum(r["vanilla_correct"] and not r["correct"] for r in g)}) fallback {sum(r["fallback"] for r in rows)} | '
                 f'items {len(mem.listed()) if spec["memory"] == "evolve" else len(run1_items(c, kk))} | {(time.time() - t0) / 60:.1f} min, '
                 f'teacher {c.costs[t]["teacher_calls"]} (${c.costs[t]["teacher_usd"]:.2f}; all ${c.teacher.spent:.2f})')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tracks')
    ap.add_argument('--max-blocks', type=int)
    ap.add_argument('--gpus')
    ap.add_argument('--config', default=CONFIG)
    a = ap.parse_args()
    c = setup(gpu=True, gpus=[int(g) for g in a.gpus.split(',')] if a.gpus else None, config=a.config)
    names = a.tracks.split(',') if a.tracks else list(c.tracks)
    stopped = []
    try:
        with ThreadPoolExecutor(len(names)) as ex:
            futures = {t: ex.submit(run_track, c, t, a.max_blocks) for t in names}
            for t, f in futures.items():
                try:
                    f.result()
                except S.FATAL as exc:
                    stopped.append(t)
                    S.log(c, f'{t}: stopped ({type(exc).__name__}: {exc})')
    finally:
        c.pool.close()
        S.log(c, f'exit; costs {json.dumps({t: dict(v) for t, v in c.costs.items()})}')
    if stopped:
        sys.exit(f'tracks stopped early: {stopped}')


