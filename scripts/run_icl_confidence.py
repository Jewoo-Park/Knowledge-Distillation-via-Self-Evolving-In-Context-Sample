"""Confidence-gated in-context samples on Urban (2026-10-30). Protocol: results_oct/results_icl_confidence/protocol.md.

Each block of 50 questions: the vanilla answer first; a label-free gate marks low-confidence questions (experiment 1:
a risk score above the 65th percentile of the earlier questions' risk scores; experiment 2: the answer changes when
the options are relabelled, a second student call); a gated question is answered again with one example from this
track's memory (active + held items of other videos whose source question is close enough; 'util' picks among the 3
closest by the item's shrunk online net gain); an invalid second answer falls back to the vanilla answer. Only after
the block's final answers are fixed are its labels used: item utilities, the k-NN difficulty history and, for the
'evolve' tracks, run1's five teacher/critic stages (stage 1 told which cases were low confidence; stage 4 tries all
candidates of a block on one shared validation set of past low-confidence questions, scored as (fixes - breaks) / n).

Tracks (configs/icl_confidence.yaml) keep separate memories, utilities and statistics and answer the same questions in
the same order. 'run1' tracks use run1's frozen snapshots (no teacher). Generations are reused across tracks and
earlier runs when the input signature is identical.

    fuzzy35/bin/python scripts/run_icl_confidence.py [--tracks X1_gate,X2_gate] [--max-blocks N]
    fuzzy35/bin/python scripts/icl_confidence_analysis.py      # comparisons, decomposition, sensitivity
"""
