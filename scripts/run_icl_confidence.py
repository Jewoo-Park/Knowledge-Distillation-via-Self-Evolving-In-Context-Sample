def setup(gpu=True, gpus=None, config=None, check_p1=True):
    c = S.setup(config or CONFIG, gpu=gpu, gpus=gpus)
    c.identity_ref = dict(next(iter(c.vanilla.values()))['identity'], device='cuda:0')  # signatures without a GPU pool
    cf = c.cfg['confidence']
    c.cf = cf
    c.caches = [c.db] + [sqlite3.connect(f'file:{p}?mode=ro', uri=True, check_same_thread=False)
                         for p in c.cfg['generation_caches'] if Path(p).exists()]  # moved runs: skipped
    c.group = {s: S.video_group(v) for s, v in c.video.items()}
    c.tracks = cf['tracks']
    if cf['risk_signal'] == 'answer_prob':  # earlier Urban experiment 1 (scripts not in this repo)
        import answer_confidence as AC
        c.risk = AC.load()
    else:
        c.risk = None
    if cf['risk_signal'] == 'p1':  # absolute gate: vanilla answer-letter probability below p1_threshold, or unreadable
        c.p1 = (dict(sqlite3.connect(f'file:{cf["p1_db"]}?mode=ro', uri=True).execute('SELECT sample_id, p1 FROM a'))
                if Path(cf['p1_db']).exists() else {})
        missing = [s for t in c.tracks for s in c.order[t] if s not in c.p1]
        if missing and check_p1:
            raise RuntimeError(f'{len(missing)} questions without a p1 record in {cf["p1_db"]}, e.g. {missing[:3]}')
    for k in range(1, 10 ** 4) if c.cfg.get('videosis_rows') else ():  # VideoSIS vanilla: generated by its own run
        p = Path(c.cfg['videosis_rows']) / f'block_{k:04d}.json'
        if not p.exists():
            break
        for r in json.loads(p.read_text()):
            v = r['vanilla']
            c.vanilla[r['sample_id']] = {'raw': v['output'], 'answer': v['answer'], 'valid': bool(v['valid']),
                                         'correct': bool(v['correct']), 'identity': c.identity_ref}
    missing = [s for t in c.tracks for s in c.order[t] if s not in c.vanilla]
    if missing:
        raise RuntimeError(f'{len(missing)} questions without a vanilla answer, e.g. {missing[:3]}')
    if cf.get('max_worked_chars'):
        limit_examples(cf['max_worked_chars'])
    c.costs = defaultdict(Counter)  # track -> counts (student calls by kind, new generations, teacher calls)
    c.cost_lock = threading.Lock()
    c.snap = {}
    return c


def signature(c, x, parts):
    s = c.cfg['student']
    ident = c.pool.runtime_identity if c.pool is not None else c.identity_ref
    return digest({'sample': x.sample_id, 'parts': parts, 'system': c.system, 'seed': R.seed_of(c, x.sample_id),
                   'identity': ident, 'generation': s['generation'], 'video': s['video']})


def gen(c, plans, kind=None):
    """R.generate with every earlier prediction store as a read-only cache; counts calls per track and kind."""
    kind = kind or getattr(LOCAL, 'kind', 'trial')
    out, todo = [None] * len(plans), {}
    for i, p in enumerate(plans):
        x = p['sample']
        if p['parts'] is None:
            v = c.vanilla[x.sample_id]
            out[i] = {'raw': v['raw'], 'answer': v['answer'], 'valid': v['valid'], 'correct': v['correct'], 'source': 'vanilla'}
            continue
        sig = signature(c, x, p['parts'])
        row = None
        for db in c.caches:
            row = db.execute('SELECT raw, answer, valid, correct FROM p WHERE signature=?', (sig,)).fetchone()
            if row:
                break
        if row:
            out[i] = {'raw': row[0], 'answer': row[1], 'valid': bool(row[2]), 'correct': bool(row[3]), 'source': 'store'}
        else:
            todo.setdefault(sig, (x, p['parts'], []))[2].append(i)
    with c.cost_lock:
        c.costs[getattr(LOCAL, 'track', '?')][f'{kind}_calls'] += sum(p['parts'] is not None for p in plans)
        c.costs[getattr(LOCAL, 'track', '?')][f'{kind}_new'] += len(todo)
    if todo:
        if c.pool is None:
            raise RuntimeError(f'{len(todo)} generations missing and no GPU pool (dry run)')
        jobs = list(todo.items())
        with c.gpu_lock:
            for start in range(0, len(jobs), 64):
                chunk = jobs[start:start + 64]
                tasks = [(x.model_input(), '', R.seed_of(c, x.sample_id), c.system) for _, (x, _, _) in chunk]
                t0 = time.time()
                gens = c.pool.generate_many(tasks, kwargs=[{'parts': parts} for _, (_, parts, _) in chunk])
                per = (time.time() - t0) / max(len(chunk), 1)
                for (sig, (x, parts, idx)), g in zip(chunk, gens):
                    parsed = parse_answer(g.raw_output, x.choices)
                    ok = bool(is_correct(parsed, x.ground_truth, x.choices))
                    c.db.execute('INSERT OR IGNORE INTO p VALUES (?,?,?,?,?,?,?,?,?,?)',
                                 (sig, x.sample_id, g.raw_output, parsed.answer, int(parsed.valid), int(ok),
                                  g.runtime.get('input_tokens'), g.runtime.get('generated_tokens'), round(per, 2), now()))
                    for i in idx:
                        out[i] = {'raw': g.raw_output, 'answer': parsed.answer, 'valid': parsed.valid, 'correct': ok,
                                  'source': 'generated'}
    return out


def teacher_call(c, kind, prompt, blocks, schema):
    t = getattr(LOCAL, 'track', '?')
    with c.cost_lock:
        if c.costs[t]['teacher_calls'] >= c.cf['teacher_calls_per_track']:
            raise S.TeacherBudgetExceeded(f'{t}: {c.cf["teacher_calls_per_track"]} teacher/critic calls used')
        c.costs[t]['teacher_calls'] += 1
        c.costs[t][f'teacher_{kind}'] += 1
    out = c.teacher.call(kind, prompt, blocks, schema)
    with c.cost_lock:
        c.costs[t]['teacher_usd'] = round(c.costs[t]['teacher_usd'] + getattr(c.teacher.local, 'cost', 0.0), 4)
    return out


def limit_examples(n):
    """Example texts (worked_output) of at most n characters: stated in the stage 3-5 prompts and enforced wherever a
    worked_output is accepted (a longer one is rejected like one that does not answer its correct option)."""
    import src.icl.stage_memory as SM
    orig = SM.answers

    def answers(text, choices, truth):
        out = orig(text, choices, truth)
        return out if out is not None and len(out) <= n else None
    SM.answers = S.answers = answers
    rule = (f'\n\nLength limit: every worked_output must be at most {n} characters. A longer worked_output is rejected '
            f'(long examples made the student ramble past its output limit). Keep only the observations and steps that decide '
            f'the answer.')
    S.STAGE3_PROMPT += rule
    S.STAGE4_PROMPT += rule
    S.STAGE5_PROMPT += rule


# ------------------------------------------------------------------ memory, gate and selection
def run1_items(c, k):
    """run1's items after block k-1 (active + held), frozen."""
    if k not in c.snap:
        p = Path(c.cf['run1_memory']) / f'block_{k - 1:04d}.json'
        c.snap[k] = [i for i in json.loads(p.read_text()) if i['status'] in ('active', 'hold')] if k > 1 and p.exists() else []
    return c.snap[k]


def candidates(c, x, items):
    """Eligible items (S.eligible: other videos, not the identical question, correct option text not among the current
    options), by the cosine of their source question with this question, best first."""
    pool = S.eligible(c, x, items)
    q = c.vec[x.sample_id]
    return sorted(((float(c.vec[i['sample_id']] @ q), i) for i in pool), key=lambda t: (-t[0], t[1]['id']))


def utility(st, m):
    n, fix, brk = st
    return (fix - brk) / (n + m)


def select(c, t, x, items, util):
    """-> (item or None, record). sim: the closest appropriate item; util: among the top_n appropriate items the one
    with the best shrunk net gain, none when that is below min_utility."""
    cf = c.cf
    ranked = candidates(c, x, items)
    ok = [(s, i) for s, i in ranked if s >= cf['tau']]
    rec = {'top': [{'id': i['id'], 'version': i['version'], 'score': round(s, 4)} for s, i in ranked[:3]], 'appropriate': len(ok)}
    if not ok:
        return None, dict(rec, why='no item above tau')
    if c.tracks[t]['select'] == 'sim':
        return ok[0][1], dict(rec, score=round(ok[0][0], 4))
    scored = [(utility(util[f'{i["id"]}@{i["version"]}'], cf['m']), s, i) for s, i in ok[:cf['top_n']]]
    u, s, i = max(scored, key=lambda z: (z[0], z[1]))
    rec.update(utilities={f'{i2["id"]}@{i2["version"]}': round(u2, 4) for u2, _, i2 in scored})
    if u < cf['min_utility']:
        return None, dict(rec, why='best utility below min_utility')
    return i, dict(rec, score=round(s, 4), utility=round(u, 4))


def knn_risk(c, x, past):
    """1 - vanilla accuracy of the knn nearest questions answered in earlier blocks (None with too few)."""
    if len(past['ids']) < c.cf['min_history']:
        return None
    sims = past['vecs'] @ c.vec[x.sample_id]
    top = np.argsort(-sims)[:c.cf['knn']]
    return 1.0 - float(np.mean(past['correct'][top]))


def relabelled(c, ids):
    plans, backs = [], []
    for s in ids:
        import ics_followup as F  # earlier Urban experiment 2 (scripts not in this repo)
        parts, back, _ = F.permuted_question(c.samples[s], c.cf['relabel_seed'])
        plans.append({'sample': c.samples[s], 'parts': parts})
        backs.append(back)
    res = gen(c, plans, 'relabel')
    out = []
    for r, back in zip(res, backs):
        out.append(back.get(r['answer']) if r['valid'] and r['answer'] else None)
    return out


# ------------------------------------------------------------------ one block
def answer_block(c, t, k, mem, st):
    spec, cf = c.tracks[t], c.cf
    ids = c.blocks[t][k - 1]
    items = mem.listed() if spec['memory'] == 'evolve' else run1_items(c, k)
    van = {s: c.vanilla[s] for s in ids}
    gate, extra = {}, {}
    if spec['gate'] == 'p1':
        for s in ids:
            p1 = c.p1[s]
            gate[s] = p1 is None or p1 < cf['p1_threshold']
            extra[s] = {'p1': None if p1 is None else round(p1, 6), 'p1_threshold': cf['p1_threshold']}
    elif spec['gate'] == 'relabel':
        rl = relabelled(c, ids)
        for s, a in zip(ids, rl):
            va = van[s]['answer'] if van[s]['valid'] else None
            gate[s] = (a != va) or a is None or va is None
            extra[s] = {'relabel_answer': a}
    else:
        hist = st['risk_hist']
        thr = float(np.percentile(hist, 100 * (1 - cf['budget']))) if len(hist) >= cf['min_history'] else None
        for s in ids:
            if cf['risk_signal'] == 'answer_prob':
                risk = c.risk[s]['risk'] if s in c.risk else None
            else:
                risk = knn_risk(c, c.samples[s], st['past'])
            gate[s] = thr is not None and risk is not None and risk >= thr
            extra[s] = {'risk': None if risk is None else round(risk, 4), 'risk_threshold': None if thr is None else round(thr, 4)}
    chosen, sel = {}, {}
    for s in ids:
        if gate[s]:
            item, rec = select(c, t, c.samples[s], items, st['util'])
            sel[s] = rec
            if item is not None:
                chosen[s] = item
    plans = [{'sample': c.samples[s], 'parts': S.parts_for(c, c.samples[s], chosen[s])} for s in ids if s in chosen]
    res = dict(zip([s for s in ids if s in chosen], gen(c, plans, 'icl'))) if plans else {}
    with c.cost_lock:
        c.costs[t]['vanilla_calls'] += len(ids)
    rows = []
    for j, s in enumerate(ids, 1):
        x, v = c.samples[s], van[s]
        r = res.get(s)
        use = r is not None and r['valid']  # an invalid second answer falls back to the vanilla answer
        final = r if use else {'answer': v['answer'], 'correct': v['correct'], 'valid': v['valid'], 'raw': v['raw'], 'source': 'vanilla'}
        item = chosen.get(s)
        rows.append({'benchmark': t, 'block': k, 'index': (k - 1) * c.cfg['block_size'] + j, 'sample_id': s,
                     'video': c.video[s], 'group': c.group[s], 'gated': bool(gate[s]), **extra[s],
                     'selection': sel.get(s), 'icl_valid': None if r is None else bool(r['valid']),
                     'icl_answer': None if r is None else r['answer'], 'icl_correct': None if r is None else bool(r['correct']),
                     'fallback': r is not None and not r['valid'],
                     'shown': [{'id': item['id'], 'version': item['version'], 'kind': item.get('kind'),
                                'score': (sel.get(s) or {}).get('score')}] if item is not None and use else [],
                     'tried': None if item is None else {'id': item['id'], 'version': item['version']},
                     'student_input_text': None if item is None else [p for p in S.parts_for(c, x, item) if p != VIDEO],
                     'student': {'answer': final['answer'], 'correct': final['correct'], 'valid': final['valid'],
                                 'output': final['raw'], 'source': final['source']},
                     'vanilla': {'answer': v['answer'], 'correct': v['correct'], 'valid': v['valid'], 'output': v['raw']},
                     'correct': bool(final['correct']), 'vanilla_correct': bool(v['correct'])})
    return rows


def after_block(c, t, rows, st):
    """Labels of the answered block: utilities (final vs vanilla, per item version), risk and k-NN histories."""
    for r in rows:
        if r['tried']:
            u = st['util'][f'{r["tried"]["id"]}@{r["tried"]["version"]}']
            u[0] += 1
            u[1] += int(r['correct'] and not r['vanilla_correct'])
            u[2] += int(r['vanilla_correct'] and not r['correct'])
        if r.get('risk') is not None:
            st['risk_hist'].append(r['risk'])
    p = st['past']
    vec = np.stack([c.vec[r['sample_id']] for r in rows])
    p['vecs'] = vec if p['vecs'] is None else np.vstack([p['vecs'], vec])
    p['correct'] = np.concatenate([p['correct'], [float(r['vanilla_correct']) for r in rows]])
    p['ids'] += [r['sample_id'] for r in rows]


def new_state():
    return {'util': defaultdict(lambda: [0, 0, 0]), 'risk_hist': [], 'past': {'vecs': None, 'correct': np.zeros(0), 'ids': []}}


